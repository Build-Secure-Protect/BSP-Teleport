def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    out = root / "src/main/resources/assets/bsp_teleport/lang/en_us.json"
    data = {}
    data.update(OTHER)
    for key, text in MESSAGES.items():
        data["message.bsp_teleport." + key] = text
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, indent=2, ensure_ascii=True) + "\n")
    print("wrote", out.relative_to(root), len(data), "keys")


if __name__ == "__main__":
    main()
